CREATE TABLE expenses (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 invoice_number VARCHAR(100) NULL,
 expense_date DATE NOT NULL,
 supplier_id BIGINT UNSIGNED NULL,
 supplier_name_snapshot VARCHAR(1000) NOT NULL,
 supplier_version BIGINT UNSIGNED NOT NULL,
 category VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 taxable_amount DECIMAL(18,2) NOT NULL,
 exempt_amount DECIMAL(18,2) NOT NULL,
 tax_rate DECIMAL(5,4) NOT NULL,
 tax_amount DECIMAL(18,2) NOT NULL,
 total DECIMAL(18,2) NOT NULL,
 notes TEXT NOT NULL,
 calculator_version SMALLINT UNSIGNED NOT NULL,
 version BIGINT UNSIGNED NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 updated_by BIGINT UNSIGNED NOT NULL,
 team_id BIGINT UNSIGNED NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 deleted_at DATETIME(6) NULL,
 deleted_by BIGINT UNSIGNED NULL,
 delete_reason VARCHAR(1000) NULL,
 FOREIGN KEY(supplier_id) REFERENCES suppliers(id),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(updated_by) REFERENCES users(id),
 FOREIGN KEY(deleted_by) REFERENCES users(id),
 FOREIGN KEY(team_id) REFERENCES teams(id),
 INDEX expense_date_index(expense_date,id),
 INDEX expense_supplier(supplier_id,id),
 INDEX expense_owner(created_by,id),
 INDEX expense_team(team_id,id),
 INDEX expense_currency(currency,expense_date,id),
 INDEX expense_category(category,expense_date,id),
 INDEX expense_deleted(deleted_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
INSERT IGNORE INTO permissions(name) VALUES('gastos.view'),('gastos.create'),('gastos.update'),('gastos.delete'),('gastos.restore');
