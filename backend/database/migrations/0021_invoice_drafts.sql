CREATE TABLE invoices (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 invoice_number VARCHAR(80) NULL UNIQUE,
 sar_snapshot_json JSON NULL,
 status VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 customer_id BIGINT UNSIGNED NULL,
 customer_version BIGINT UNSIGNED NOT NULL,
 customer_name_snapshot VARCHAR(1000) NOT NULL,
 customer_rtn_snapshot VARCHAR(30) NOT NULL,
 customer_contact_snapshot VARCHAR(120) NOT NULL,
 customer_phone_snapshot VARCHAR(50) NOT NULL,
 customer_email_snapshot VARCHAR(254) NOT NULL,
 customer_address_snapshot VARCHAR(1000) NOT NULL,
 invoice_date DATE NOT NULL,
 payment_term_type VARCHAR(7) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 credit_days SMALLINT UNSIGNED NULL,
 currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 public_notes TEXT NOT NULL,
 exoneration_reference VARCHAR(500) NOT NULL,
 general_discount_type VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 general_discount DECIMAL(20,4) NOT NULL,
 gross DECIMAL(18,2) NOT NULL,
 item_discount DECIMAL(18,2) NOT NULL,
 allocated_discount DECIMAL(18,2) NOT NULL,
 base_15 DECIMAL(18,2) NOT NULL,
 base_18 DECIMAL(18,2) NOT NULL,
 exempt DECIMAL(18,2) NOT NULL,
 exonerated DECIMAL(18,2) NOT NULL,
 isv_15 DECIMAL(18,2) NOT NULL,
 isv_18 DECIMAL(18,2) NOT NULL,
 total DECIMAL(18,2) NOT NULL,
 products_investment DECIMAL(18,2) NOT NULL,
 additional_expenses DECIMAL(18,2) NOT NULL,
 investment_total DECIMAL(18,2) NOT NULL,
 profit DECIMAL(18,2) NOT NULL,
 paid_total DECIMAL(18,2) NOT NULL,
 balance DECIMAL(18,2) NOT NULL,
 calculator_version SMALLINT UNSIGNED NOT NULL,
 profit_version SMALLINT UNSIGNED NOT NULL,
 version BIGINT UNSIGNED NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 updated_by BIGINT UNSIGNED NOT NULL,
 team_id BIGINT UNSIGNED NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 FOREIGN KEY(customer_id) REFERENCES customers(id),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(updated_by) REFERENCES users(id),
 FOREIGN KEY(team_id) REFERENCES teams(id),
 INDEX invoice_owner(created_by,id),
 INDEX invoice_team(team_id,id),
 INDEX invoice_customer(customer_id,id),
 INDEX invoice_date_index(invoice_date,id),
 INDEX invoice_status(status,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE invoice_items (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 invoice_id BIGINT UNSIGNED NOT NULL,
 position SMALLINT UNSIGNED NOT NULL,
 description VARCHAR(4000) NOT NULL,
 unit VARCHAR(40) NOT NULL,
 quantity DECIMAL(18,4) NOT NULL,
 unit_price DECIMAL(18,6) NOT NULL,
 unit_cost DECIMAL(18,6) NOT NULL,
 discount_type VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 discount DECIMAL(18,6) NOT NULL,
 tax_type VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 unit_discount DECIMAL(26,12) NOT NULL,
 gross DECIMAL(18,2) NOT NULL,
 item_discount DECIMAL(18,2) NOT NULL,
 allocated_discount DECIMAL(18,2) NOT NULL,
 base DECIMAL(18,2) NOT NULL,
 line_cost DECIMAL(18,2) NOT NULL,
 FOREIGN KEY(invoice_id) REFERENCES invoices(id),
 UNIQUE KEY invoice_item_position(invoice_id,position),
 UNIQUE KEY invoice_item_owner(invoice_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
