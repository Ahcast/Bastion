CREATE TABLE quotes (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 number VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 status VARCHAR(32) CHARACTER SET ascii NOT NULL,
 source_process_id BIGINT UNSIGNED NULL,
 customer_id BIGINT UNSIGNED NULL,
 customer_version BIGINT UNSIGNED NOT NULL,
 customer_name_snapshot VARCHAR(1000) NOT NULL,
 customer_rtn_snapshot VARCHAR(30) NOT NULL,
 customer_contact_snapshot VARCHAR(120) NOT NULL,
 customer_phone_snapshot VARCHAR(50) NOT NULL,
 customer_email_snapshot VARCHAR(254) NOT NULL,
 customer_address_snapshot VARCHAR(1000) NOT NULL,
 process_reference_snapshot VARCHAR(500) NOT NULL,
 date DATE NOT NULL,
 validity_days SMALLINT UNSIGNED NOT NULL,
 currency CHAR(3) CHARACTER SET ascii NOT NULL,
 terms TEXT NOT NULL,
 private_notes TEXT NOT NULL,
 author_contact VARCHAR(1000) NOT NULL,
 exoneration_reference VARCHAR(500) NOT NULL,
 general_discount_type VARCHAR(10) CHARACTER SET ascii NOT NULL,
 general_discount DECIMAL(20,4) NOT NULL,
 gross DECIMAL(18,2) NOT NULL,
 item_discount DECIMAL(18,2) NOT NULL,
 allocated_discount DECIMAL(18,2) NOT NULL,
 base_15 DECIMAL(18,2) NOT NULL,
 base_18 DECIMAL(18,2) NOT NULL,
 exempt DECIMAL(18,2) NOT NULL,
 exonerated DECIMAL(18,2) NOT NULL,
 isv_15 DECIMAL(18,2) NOT NULL,
 isv_18 DECIMAL(18,2) NOT NULL,
 total DECIMAL(18,2) NOT NULL,
 cost DECIMAL(18,2) NOT NULL,
 margin DECIMAL(18,2) NOT NULL,
 calculator_version SMALLINT UNSIGNED NOT NULL,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 created_by BIGINT UNSIGNED NOT NULL,
 updated_by BIGINT UNSIGNED NOT NULL,
 team_id BIGINT UNSIGNED NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 deleted_at DATETIME(6) NULL,
 FOREIGN KEY(source_process_id) REFERENCES processes(id),
 FOREIGN KEY(customer_id) REFERENCES customers(id),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(updated_by) REFERENCES users(id),
 FOREIGN KEY(team_id) REFERENCES teams(id),
 INDEX quote_owner(created_by,id),INDEX quote_team(team_id,id),INDEX quote_process(source_process_id,id),INDEX quote_date(date,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
